type token struct {
	id   uint32 // Will be generated by the parser
	typ  tokenType
	text string // Generated by the Scanner
	line int
	col  int
}

type tokenType int8

const (
	character tokenType = iota // Normal words
	// '...'
	maybe       // ?
	oneormore   // +
	anyno       // *
	bracks      // (...)
	option      // |
	padding     // just to account for my bad indexing skills
	regexrange  // [...]
	infinite    // ^
	probability // <...>
	identifier  // Normal words
	str         // '...'
	regex       // [...]
	bracopen    // (
	bracclose   // )
	colon
	semicolon
)

func (t tokenType) String() string {
	switch t {
	case character:
		return "character"
	case maybe:
		return "maybe"
	case oneormore:
		return "oneormore"
	case anyno:
		return "anyno"
	case bracks:
		return "bracks"
	case option:
		return "option"
	case padding:
		return "padding"
	case regexrange:
		return "regexrange"
	case infinite:
		return "infinite"
	case probability:
		return "probability"
	case identifier:
		return "identifier"
	case str:
		return "str"
	case regex:
		return "regex"
	case bracopen:
		return "bracopen"
	case bracclose:
		return "bracclose"
	case colon:
		return "colon"
	case semicolon:
		return "semicolon"
	default:
		return fmt.Sprintf("tokenType(%d)", int(t))
	}
}

type graphbuilder struct {
	grammar string
	pars    parser
}

func newGraphBuilder() graphbuilder {
	return graphbuilder{
		pars: newParser(),
	}
}

// wordsPattern matches a one-line directive of the form:
//
//	@words identifier = count, total, index;
//
// Directives are removed before the normal grammar is scanned. They are kept
// separate from rules so a word list can be used for any non-terminal.
var wordsPattern = regexp.MustCompile(`(?m)^[ \t]*@(?:words|keywords)[ \t]+([A-Za-z_][A-Za-z0-9_]*)[ \t]*(?:=|:)[ \t]*([^\n;]*);?[ \t]*$`)

// extractWords pulls @words directives out of a grammar and returns the
// remaining grammar plus a map of rule name to words.
func extractWords(grammar string) (string, map[string][]string, error) {
	words := make(map[string][]string)
	matches := wordsPattern.FindAllStringSubmatchIndex(grammar, -1)
	if len(matches) == 0 {
		return grammar, words, nil
	}

	var out strings.Builder
	last := 0
	for _, m := range matches {
		out.WriteString(grammar[last:m[0]])
		last = m[1]
		name := grammar[m[2]:m[3]]
		raw := grammar[m[4]:m[5]]
		list := splitWords(raw)
		if len(list) == 0 {
			return "", nil, fmt.Errorf("@words/@keywords %s: expected at least one word", name)
		}
		words[name] = list
	}
	out.WriteString(grammar[last:])
	return out.String(), words, nil
}

func splitWords(raw string) []string {
	fields := strings.FieldsFunc(raw, func(r rune) bool {
		return r == ',' || r == ' ' || r == '\t' || r == '\n' || r == '\r'
	})
	out := make([]string, 0, len(fields))
	for _, f := range fields {
		if f != "" {
			out = append(out, f)
		}
	}
	return out
}

func (g *graphbuilder) startGeneration(grammar string) error {
	g.grammar = grammar
	return g.generateGraph()
}

func (g *graphbuilder) generateGraph() error {
	cleaned, words, err := extractWords(g.grammar)
	if err != nil {
		return err
	}
	g.grammar = cleaned
	tokens, scanErrs := extracttokens(g.grammar)

	if len(scanErrs) != 0 {
		all := make([]error, 0, len(scanErrs))
		for _, err := range scanErrs {
			all = append(all, fmt.Errorf("ERROR Scanning grammar >>> %s", err.String()))
		}
		return errors.Join(all...)
	}
	g.pars.tokens = tokens
	g.pars.words = words
	g.pars.graph.charmap = g.pars.charmap
	g.pars.graph.namemap = g.pars.nameMap
	g.pars.graph.regexhandler = g.pars.regexhandler
	g.pars.parseGrammar()
	g.pars.attachWords()

	// collect parse errors
	all := make([]error, 0, len(g.pars.errors))
	for _, err := range g.pars.errors {
		all = append(all, fmt.Errorf("ERROR Parsing >>> %s", err.Error()))
	}

	// collect validation errors
	for _, err := range g.pars.ValidateGraph() {
		all = append(all, fmt.Errorf("ERROR Validating >>> %s", err.Error()))
	}

	if len(all) > 0 {
		return errors.Join(all...)
	}
	return nil
}
